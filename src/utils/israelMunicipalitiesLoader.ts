export interface GeoJSONFeature {
  type: string;
  geometry: {
    type: string;
    coordinates: any[];
  };
  properties?: Record<string, any>;
}

export interface GeoJSONFeatureCollection {
  type: string;
  features: GeoJSONFeature[];
}

// Load Israel municipality GeoJSON file
export const loadIsraelMunicipalityGeoJSON = async (
  municipalityName: string
): Promise<GeoJSONFeatureCollection | null> => {
  try {
    const fileName = `${municipalityName.toLowerCase()}.geojson`;
    const url = `/israel-municipalities-polygons-master/${municipalityName}/${encodeURIComponent(
      fileName
    )}`;

    console.log(`Loading Israel municipality GeoJSON from: ${url}`);

    const response = await fetch(url);

    if (!response.ok) {
      console.error(
        `Failed to load ${fileName}: ${response.status} ${response.statusText}`
      );
      return null;
    }

    const data = await response.json();

    // Handle both Feature and FeatureCollection formats
    let featureCollection: GeoJSONFeatureCollection;

    if (data.type === "Feature") {
      // Convert single Feature to FeatureCollection
      featureCollection = {
        type: "FeatureCollection",
        features: [data],
      };
    } else if (data.type === "FeatureCollection") {
      featureCollection = data;
    } else {
      console.error(`Invalid GeoJSON format for ${fileName}:`, data);
      return null;
    }

    console.log(`Successfully loaded ${fileName}:`, featureCollection);
    return featureCollection;
  } catch (error) {
    console.error(`Error loading GeoJSON for ${municipalityName}:`, error);
    return null;
  }
};

// Format municipality name for display (replace underscores with spaces and capitalize)
export const formatMunicipalityName = (name: string): string => {
  return name
    .split("_")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
};
